package com.livio.dto;

public class GoogleMapsPgDto {

    private String inputId;
    private String link;
    private String title;
    private String category;
    private String address;
    private String openHours;
    private String website;
    private String phone;
    private String reviewCount;
    private String reviewRating;
    private String latitude;
    private String longitude;
    private String placeId;
    private String thumbnail;
    private String completeAddress;

    public GoogleMapsPgDto() {}

    public String getInputId() { return inputId; }
    public void setInputId(String inputId) { this.inputId = inputId; }
    public String getLink() { return link; }
    public void setLink(String link) { this.link = link; }
    public String getTitle() { return title; }
    public void setTitle(String title) { this.title = title; }
    public String getCategory() { return category; }
    public void setCategory(String category) { this.category = category; }
    public String getAddress() { return address; }
    public void setAddress(String address) { this.address = address; }
    public String getOpenHours() { return openHours; }
    public void setOpenHours(String openHours) { this.openHours = openHours; }
    public String getWebsite() { return website; }
    public void setWebsite(String website) { this.website = website; }
    public String getPhone() { return phone; }
    public void setPhone(String phone) { this.phone = phone; }
    public String getReviewCount() { return reviewCount; }
    public void setReviewCount(String reviewCount) { this.reviewCount = reviewCount; }
    public String getReviewRating() { return reviewRating; }
    public void setReviewRating(String reviewRating) { this.reviewRating = reviewRating; }
    public String getLatitude() { return latitude; }
    public void setLatitude(String latitude) { this.latitude = latitude; }
    public String getLongitude() { return longitude; }
    public void setLongitude(String longitude) { this.longitude = longitude; }
    public String getPlaceId() { return placeId; }
    public void setPlaceId(String placeId) { this.placeId = placeId; }
    public String getThumbnail() { return thumbnail; }
    public void setThumbnail(String thumbnail) { this.thumbnail = thumbnail; }
    public String getCompleteAddress() { return completeAddress; }
    public void setCompleteAddress(String completeAddress) { this.completeAddress = completeAddress; }
}
